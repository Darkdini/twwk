function tryPercent(s, steps) {
  const t = norm(s).replace(/,(?=\d)/g, '.');
  let m;
  // «сколько процентов X от Y» / «X это сколько процентов от Y»
  if ((m = t.match(/(\d+(?:\.\d+)?)\D+(?:сколько\s+процент[а-яё]*|какой\s+процент)\D+(\d+(?:\.\d+)?)/)) ||
      (m = t.match(/сколько\s+процент[а-яё]*\D+(\d+(?:\.\d+)?)\D+от\D+(\d+(?:\.\d+)?)/))) {
    const a = +m[1], b = +m[2]; const r = a / b * 100;
    steps.push(`Доля: ${fmt(a)} ÷ ${fmt(b)} × 100%`);
    return `${fmt(a)} — это **${fmt(r)}%** от ${fmt(b)}.`;
  }
  // «X% от Y» / «X процентов от Y»
  if ((m = t.match(/(\d+(?:\.\d+)?)\s*(?:%|процент[а-яё]*)\s+от\s+(\d+(?:\.\d+)?)/))) {
    const a = +m[1], b = +m[2]; const r = a / 100 * b;
    steps.push(`${fmt(a)}% от ${fmt(b)} = ${fmt(a)} ÷ 100 × ${fmt(b)}`);
    return `${fmt(a)}% от ${fmt(b)} = **${fmt(r)}**.`;
  }
  return null;
}

