const WDAYS = ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'];
const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];
function tryDateTime(s, steps) {
  const t = norm(s);
  const now = new Date();
  if (/(который\s+час|сколько\s+(сейчас\s+)?времени|текущее\s+время)/.test(t)) {
    steps.push('Беру системное время сервера');
    return `Сейчас **${now.getHours().toString().padStart(2, '0')}:${now.getMinutes().toString().padStart(2, '0')}** (время сервера).`;
  }
  if (/(какой\s+(сегодня\s+)?день|какое\s+(сегодня\s+)?число|сегодняшн[а-яё]*\s+дат|какая\s+дата|число\s+сегодня)/.test(t)) {
    steps.push('Беру системную дату сервера');
    return `Сегодня **${now.getDate()} ${MONTHS[now.getMonth()]} ${now.getFullYear()}**, ${WDAYS[now.getDay()]}.`;
  }
  if (/(какой\s+(сейчас\s+)?год|какой\s+год)/.test(t)) return `Сейчас **${now.getFullYear()}** год.`;
  // день недели для даты ДД.ММ.ГГГГ
  let m = t.match(/(\d{1,2})[.\/](\d{1,2})[.\/](\d{4})/);
  if (m && /(какой\s+день|день\s+недели)/.test(t)) {
    const d = new Date(+m[3], +m[2] - 1, +m[1]);
    steps.push('Вычисляю день недели по календарю');
    return `${m[1]}.${m[2]}.${m[3]} — это **${WDAYS[d.getDay()]}**.`;
  }
  return null;
}

