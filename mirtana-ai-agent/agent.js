function findUnit(word) {
  word = stem(norm(word));
  for (const u of UNITS) for (const n of u.names) if (stem(n) === word || n === word) return u;
  return null;
}
function tryConvert(s, steps) {
  const t = norm(s);
  let m = t.match(/(-?\d+(?:[.,]\d+)?)\s*([a-zа-я]+)\s+(?:в|to)\s+([a-zа-я]+)/);
  if (m) {
    const val = parseFloat(m[1].replace(',', '.'));
    const from = findUnit(m[2]), to = findUnit(m[3]);
    if (from && to && from.dim === to.dim) {
      const r = val * from.f / to.f;
      steps.push(`Через базовую единицу: ${fmt(val)} × ${from.f} ÷ ${to.f}`);
      return `${fmt(val)} ${m[2]} = **${fmt(r)} ${m[3]}**.`;
    }
  }
  // температура
  m = t.match(/(-?\d+(?:[.,]\d+)?)\s*(?:градус[а-яё]*\s*)?(цельси[а-яё]*|фаренгейт[а-яё]*|c|с|ц|f|ф)\s+(?:в|to)\s+(цельси[а-яё]*|фаренгейт[а-яё]*|c|с|ц|f|ф)/);
  if (m) {
    const val = parseFloat(m[1].replace(',', '.'));
    const isF = (x) => /^(f|ф|фаренгейт)/.test(x);
    if (isF(m[2]) && !isF(m[3])) { const r = (val - 32) * 5 / 9; steps.push('(°F − 32) × 5/9'); return `${fmt(val)}°F = **${fmt(r)}°C**.`; }
    if (!isF(m[2]) && isF(m[3])) { const r = val * 9 / 5 + 32; steps.push('°C × 9/5 + 32'); return `${fmt(val)}°C = **${fmt(r)}°F**.`; }
  }
  return null;
}

