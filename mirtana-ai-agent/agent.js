function tryChitChat(s, steps) {
  const t = norm(s);
  if (/^(привет|здравствуй|здраствуй|хай|здаров|доброе утро|добрый день|добрый вечер|хеллоу|hello|hi)/.test(t)) {
    steps.push('Распознал приветствие');
    return `Привет! Я ${AGENT_NAME} — встроенный ИИ-советник Миртаны. Могу посчитать математику, перевести величины, ` +
      `подсказать по игре или ответить на вопрос из своей базы знаний. Спрашивай!`;
  }
  if (/(как\s+(тебя\s+)?зовут|кто\s+ты|ты\s+кто|что\s+ты\s+(умеешь|можешь)|твои\s+возможност|что\s+умеешь|чем\s+помож|расскажи\s+о\s+себе)/.test(t)) {
    steps.push('Вопрос о моей личности и возможностях');
    return `Я **${AGENT_NAME}**, собственный ИИ-агент игры Миртана. Работаю полностью внутри сервера, без интернета и сторонних сервисов.\n\n` +
      `Что я умею:\n• 🧮 математика (арифметика, степени, корни, факториал, проценты, функции);\n` +
      `• 📐 перевод величин (км↔мили, кг↔фунты, °C↔°F, время);\n• 🗓 дата, время, день недели;\n` +
      `• ⚔ советы по игре по реальным формулам (что строить, экономика, бой);\n` +
      `• 📚 ответы из базы знаний (наука, космос, география, история).`;
  }
  if (/(как\s+дела|как\s+ты|как\s+жизнь)/.test(t)) { steps.push('Светский вопрос'); return 'Всё отлично, готова думать! Чем могу помочь?'; }
  if (/(спасибо|благодар|спс|thanks)/.test(t)) { steps.push('Благодарность'); return 'Всегда пожалуйста! Обращайся ещё. 🙂'; }
  if (/(пока|до свидан|бывай|увидимся)/.test(t)) { steps.push('Прощание'); return 'До встречи! Удачи в Миртане. 👑'; }
  return null;
}

// ─────────────────────────────────────────────────────────────────────
//  ФОЛЛБЭК-РАССУЖДЕНИЕ — честный разбор, без выдумок
// ─────────────────────────────────────────────────────────────────────
function reason(s, steps) {
  const t = norm(s);
  const qword = ['почему', 'зачем', 'как', 'где', 'когда', 'кто', 'что', 'сколько', 'какой', 'какая', 'какое']
    .find(w => hasWord(t, w)) || null;
  const key = keyStems(s).slice(0, 6);
  steps.push('В базе знаний точного ответа нет — раскладываю вопрос на части');
  if (qword) steps.push(`Тип вопроса: «${qword}»`);
  if (key.length) steps.push(`Ключевые понятия: ${key.join(', ')}`);

  let msg = `Я обдумала вопрос, но точного факта по нему в моей автономной базе нет — ` +
    `я работаю офлайн, без доступа в интернет, поэтому не стану выдумывать ответ.`;
  if (qword === 'сколько' || looksLikeMath(s)) {
    msg += `\n\nЕсли это расчёт — напиши его в виде примера (например, «сколько будет 15% от 200» или «(12+3)*4»), и я посчитаю точно.`;
  } else if (key.length) {
    msg += `\n\nПопробуй переформулировать про «${key[0]}» проще или конкретнее — возможно, это есть в моей базе ` +
      `(наука, космос, география, история) или я помогу по самой игре.`;
  }
  return msg;
}

// ─────────────────────────────────────────────────────────────────────
//  ГЛАВНЫЙ ВХОД
// ─────────────────────────────────────────────────────────────────────
function ask(question, ctx = {}) {
  const steps = [];
  const q = String(question || '').trim();
  if (!q) return { answer: 'Задай вопрос — и я подумаю над ответом.', steps: [], topic: 'empty' };
  if (q.length > 600) return { answer: 'Вопрос слишком длинный. Сформулируй короче, пожалуйста.', steps: [], topic: 'toolong' };

  steps.push(`Получен вопрос (${q.length} симв.). Определяю намерение…`);

  // порядок важен: сначала точные вычисления, потом знания, потом рассуждение
  let r;

  if ((r = tryChitChat(q, steps)) != null) return { answer: r, steps, topic: 'chat' };

  if ((r = tryPercent(q, steps)) != null) { steps.unshift('Намерение: проценты'); return { answer: r, steps, topic: 'math' }; }

  if (looksLikeMath(q)) {
    steps.push('Намерение: математика — разбираю выражение рекурсивным спуском');
    try {
      const cleaned = q.replace(/(сколько\s+будет|посчитай|вычисли|чему\s+равно|реши\s+пример|\?)/g, ' ');
      const v = evalMath(cleaned);
      if (isFinite(v) || v === Infinity) {
        steps.push('Выражение разобрано и вычислено');
        return { answer: `**${fmt(v)}**`, steps, topic: 'math' };
      }
    } catch (_) {
      steps.push('Не смогла разобрать выражение однозначно');
    }
  }

  if ((r = tryConvert(q, steps)) != null) { steps.unshift('Намерение: перевод величин'); return { answer: r, steps, topic: 'convert' }; }
  if ((r = tryDateTime(q, steps)) != null) { steps.unshift('Намерение: дата/время'); return { answer: r, steps, topic: 'datetime' }; }
  if ((r = gameAdvice(q, steps, ctx.player)) != null) { steps.unshift('Намерение: совет по игре'); return { answer: r, steps, topic: 'game' }; }
  if ((r = tryKB(q, steps)) != null) { steps.unshift('Намерение: вопрос-знание'); return { answer: r, steps, topic: 'kb' }; }

  return { answer: reason(q, steps), steps, topic: 'reason' };
}

