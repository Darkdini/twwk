function norm(s) {
  return String(s || '').toLowerCase().replace(/ё/g, 'е').trim();
}
// очень лёгкий стеммер: срезаем частые русские окончания
function stem(w) {
  if (w.length <= 4) return w;
  const ends = ['иями','ями','ами','ого','его','ыми','ими','ому','ему','ешь','ете','ует',
    'ость','ение','ация','ция','ая','яя','ое','ее','ые','ие','ой','ей','ов','ев','ам','ям',
    'ах','ях','ин','ть','ла','ло','ли','ет','ут','ют','ит','ат','ят','ы','и','а','я','о','е','у','ю'];
  for (const e of ends) if (w.length - e.length >= 3 && w.endsWith(e)) return w.slice(0, -e.length);
  return w;
}
function tokens(s) {
  return norm(s).replace(/[^a-zа-я0-9ё\s]/gi, ' ').split(/\s+/).filter(Boolean);
}
function keyStems(s) {
  return tokens(s).filter(t => !STOP.has(t)).map(stem).filter(t => t.length >= 3);
}
// поиск целого слова (Cyrillic-safe: \b в JS работает только с ASCII)
function hasWord(t, w) { return new RegExp('(^|[^а-яёa-z])' + w + '([^а-яёa-z]|$)', 'i').test(t); }
function fmt(n) {
  if (!isFinite(n)) return String(n);
  if (Number.isInteger(n)) return n.toLocaleString('ru-RU');
  const r = Math.round(n * 1e6) / 1e6;
  return String(r).replace('.', ',');
}

