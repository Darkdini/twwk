function ruMathToSymbols(s) {
  return s
    .replace(/квадратн\w*\s+корень\s+из|корень\s+из|корень/g, ' sqrt ')
    .replace(/возвести\s+в\s+степень|в\s+степени|степень/g, ' ^ ')
    .replace(/умножить\s+на|умножь\s+на|умножен[а-яё]*/g, ' * ')
    .replace(/разделить\s+на|раздели\s+на|делить\s+на|делен[а-яё]*/g, ' / ')
    .replace(/плюс|прибав[а-яё]*|сложить/g, ' + ')
    .replace(/минус|вычест[а-яё]*|отнять/g, ' - ')
    .replace(/факториал/g, ' fact ')
    .replace(/\bпи\b/g, ' pi ')
    .replace(/[×х]/g, ' * ')        // символ умножения и кириллическая «х»
    .replace(/÷/g, ' / ')
    .replace(/,(?=\d)/g, '.');      // десятичная запятая → точка
}
function factorial(n) {
  if (n < 0 || !Number.isInteger(n)) return NaN;
  if (n > 170) return Infinity;
  let r = 1; for (let i = 2; i <= n; i++) r *= i; return r;
}
const FUNCS = {
  sqrt: Math.sqrt, abs: Math.abs, sin: Math.sin, cos: Math.cos, tan: Math.tan,
  ln: Math.log, log: (x) => Math.log10(x), exp: Math.exp,
  round: Math.round, floor: Math.floor, ceil: Math.ceil, fact: factorial,
};
function tokenizeMath(s) {
  const out = []; let i = 0;
  const src = s.replace(/\s+/g, ' ');
  while (i < src.length) {
    const c = src[i];
    if (c === ' ') { i++; continue; }
    if (/[0-9.]/.test(c)) {
      let j = i + 1; while (j < src.length && /[0-9.]/.test(src[j])) j++;
      out.push({ t: 'num', v: parseFloat(src.slice(i, j)) }); i = j; continue;
    }
    if (/[a-z]/i.test(c)) {
      let j = i + 1; while (j < src.length && /[a-z]/i.test(src[j])) j++;
      out.push({ t: 'name', v: src.slice(i, j).toLowerCase() }); i = j; continue;
    }
    if ('+-*/^()!'.includes(c)) { out.push({ t: c }); i++; continue; }
    i++; // прочее игнорируем
  }
  return out;
}
function evalMath(expr) {
  const tk = tokenizeMath(ruMathToSymbols(expr));
  if (!tk.length) return NaN;
  let p = 0;
  const peek = () => tk[p];
  const eat = (t) => { if (tk[p] && tk[p].t === t) return tk[p++]; throw new Error('parse'); };
  function parseExpr() {
    let v = parseTerm();
    while (peek() && (peek().t === '+' || peek().t === '-')) {
      const op = tk[p++].t; const r = parseTerm(); v = op === '+' ? v + r : v - r;
    }
    return v;
  }
  function parseTerm() {
    let v = parsePower();
    while (peek() && (peek().t === '*' || peek().t === '/')) {
      const op = tk[p++].t; const r = parsePower(); v = op === '*' ? v * r : v / r;
    }
    return v;
  }
  function parsePower() {
    let v = parseUnary();
    if (peek() && peek().t === '^') { p++; const r = parsePower(); v = Math.pow(v, r); }
    return v;
  }
  function parseUnary() {
    if (peek() && peek().t === '-') { p++; return -parseUnary(); }
    if (peek() && peek().t === '+') { p++; return parseUnary(); }
    return parsePostfix();
  }
  function parsePostfix() {
    let v = parsePrimary();
    while (peek() && peek().t === '!') { p++; v = factorial(v); }
    return v;
  }
  function parsePrimary() {
    const t = peek();
    if (!t) throw new Error('eof');
    if (t.t === 'num') { p++; return t.v; }
    if (t.t === '(') { p++; const v = parseExpr(); eat(')'); return v; }
    if (t.t === 'name') {
      p++;
      if (t.v === 'pi') return Math.PI;
      if (t.v === 'e') return Math.E;
      if (FUNCS[t.v]) {
        let arg;
        if (peek() && peek().t === '(') { p++; arg = parseExpr(); eat(')'); }
        else arg = parseUnary();
        return FUNCS[t.v](arg);
      }
      throw new Error('unknown ' + t.v);
    }
    throw new Error('unexpected');
  }
  const v = parseExpr();
  if (p < tk.length) throw new Error('trailing');
  return v;
}
function looksLikeMath(s) {
  const t = norm(s);
  if (/(сколько\s+будет|посчитай|вычисли|чему\s+равно|реши\s+пример)/.test(t)) return true;
  const hasDigit = /\d/.test(t);
  const hasOp = /[+\-*/^!×х÷]/.test(t) ||
    /(плюс|минус|умнож|раздел|делить|степен|корень|факториал|прибав|вычест|отнять)/.test(t);
  return hasDigit && hasOp;
}

